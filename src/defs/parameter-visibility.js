export function isParameterActive(parameter, params) {
  try { return typeof parameter.showIf!=='function'||!!parameter.showIf(params); }
  catch { return true; }
}
export function withParameterVisibility(def) {
  const rules=BY_NODE.get(def.key);if(!rules)return def;
  const defaults=Object.fromEntries(def.params.map(p=>[p.key,p.def]));
  return {...def,params:def.params.map(pd=>{
    const tests=rules.get(pd.key);if(!tests)return pd;
    return {...pd,showIf:input=>{
      const p={...defaults,...input};
      if(!tests.some(r=>r.replace)&&!isParameterActive(pd,p))return false;
      // Unknown selector values in old/custom projects fail open.
      if(def.params.some(d=>d.type==='select'&&d.options&&!d.options.includes(p[d.key])))return true;
      return tests.every(r=>r.test(p));
    }};
  })};
}

export function parameterPresentation(parameter, params, wired=false) {
  return isParameterActive(parameter,params)?"control":wired?"connection":"hidden";
}
