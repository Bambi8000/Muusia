/* Record node-source recency from Git, with changed working-tree nodes first.
   Run before a node release, commit the generated file. CI needs no Git history.
   Unchanged source hashes retain their metadata, so reruns are stable. */
import fs from 'node:fs';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {pathToFileURL} from 'node:url';
import path from 'node:path';
const dest='src/defs/node-recency-data.js';
const prior=fs.existsSync(dest)?(await import(pathToFileURL(path.resolve(dest)))).NODE_RECENCY:{};
const git=(...args)=>execFileSync('git',args,{encoding:'utf8',maxBuffer:20e6,stdio:['ignore','pipe','pipe']});
const log=git('log','--reverse','--format=@@%cs','--name-only','--','src/defs/nodes');
const history={};let order=0,date='';
for(const line of log.split('\n')){
 if(line.startsWith('@@')){date=line.slice(2);order++;}
 else if(/^src\/defs\/nodes\/[^/]+\.js$/.test(line))history[line]={date,order};
}
const data={},today=new Date().toISOString().slice(0,10);
for(const f of fs.readdirSync('src/defs/nodes').filter(f=>f.endsWith('.js')).sort()){
 const file='src/defs/nodes/'+f,source=fs.readFileSync(file),sha256=createHash('sha256').update(source).digest('hex');
 const {default:N}=await import(pathToFileURL(path.resolve(file)));
 if(prior[N.key]?.sha256===sha256){data[N.key]=prior[N.key];continue;}
 let committed;try{committed=git('show','HEAD:'+file);}catch{committed=null;}
 const dirty=committed===null||createHash('sha256').update(committed).digest('hex')!==sha256;
 data[N.key]={...(dirty?{date:today,order:order+1}:history[file]||{date:null,order:0}),sha256};
}
fs.writeFileSync(dest,'/* Generated by tools/make-node-recency.mjs. Dates describe node-source updates, not original invention. */\nexport const NODE_RECENCY = '+JSON.stringify(data,null,2)+';\n');
console.log('Recorded recency for '+Object.keys(data).length+' node definitions');
