/* Validator: Polyhedron Studio.
   Run from the repo root: node tools/validate-polystudio.mjs
   Uses the REAL src/defs/helpers.js and auto-switches lab <-> baked.

   The catalogue is GENERATED by three operators (rectify / truncate / dual)
   rather than tabulated, so the oracles have to prove the geometry rather
   than spot-check it:
   - Euler's formula V - E + F = 2 must hold for every solid, computed from
     the emitted mesh. A mis-wired operator breaks this immediately;
   - known face counts for the classical solids (cube 6, dodecahedron 12,
     truncated icosahedron 32, rhombic triacontahedron 30, ...);
   - the mesh payload obeys the v2.66 contract (flat, tri*9, centred,
     longest dimension exactly 1) so Mesh Slice reads it identically to an
     imported STL;
   - back-face culling really culls, and every drawn face is front-facing;
   - the silhouette is a convex hull that contains every drawn point;
   - Explode is a drawing convention and must NOT reach the mesh, while
     Stellate reshapes the real solid and must. */

import { existsSync, readFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

const LAB = "nodes-lab/polystudio.plotternode.js";
const BAKED = "src/defs/nodes/polystudio.js";

let def;
if (existsSync(LAB)) {
  console.log("[lab] " + LAB);
  const helpers = await import(pathToFileURL("src/defs/helpers.js").href);
  const body = readFileSync(LAB, "utf8").trim().replace(/;\s*$/, "");
  def = new Function(...Object.keys(helpers), "return " + body + ";")(...Object.values(helpers));
} else {
  console.log("[baked] " + BAKED);
  def = (await import(pathToFileURL(BAKED).href)).default;
}

let pass = 0, fail = 0;
const CHECK = (name, cond, extra) => {
  if (cond) { console.log("ok    " + name); pass++; }
  else { console.log("FAIL  " + name + (extra ? " - " + extra : "")); fail++; }
};

const defaults = {};
for (const q of def.params) defaults[q.key] = q.def;
const A4 = { W: 210, H: 297 }, SQ = { W: 210, H: 210 };
const run = (over, ctx = A4) => {
  const P = { ...defaults, ...over };
  return def.compute([null], P, ctx, { params: P });
};
const facesOf = (o) => o[0], silOf = (o) => o[1], meshOf = (o) => o[2];
const allPts = (ps) => ps.paths.flatMap((q) => q.pts);
const finite = (ps) => allPts(ps).every((q) => Number.isFinite(q[0]) && Number.isFinite(q[1]));
const sig = (o) => JSON.stringify(facesOf(o).paths);

const SHAPES = def.params.find((q) => q.key === "shape").options;
CHECK("21 shapes in the catalogue", SHAPES.length === 21, String(SHAPES.length));
CHECK("three outputs: Faces, Silhouette, Mesh",
  def.outs.length === 3 && def.outs[0].type === "paths" && def.outs[1].type === "paths" && def.outs[2].type === "mesh");

/* --- every shape: renders, finite, deterministic, budget, pens --- */
for (const shape of SHAPES) {
  const o = run({ shape });
  const F = facesOf(o), S = silOf(o), M = meshOf(o);
  CHECK("[" + shape + "] renders faces + silhouette + mesh",
    F.paths.length > 0 && S.paths.length === 1 && !!M && M.kind === "mesh",
    F.paths.length + " / " + S.paths.length + " / " + (M ? M.tri : "no mesh"));
  CHECK("[" + shape + "] finite, in budget, valid pens",
    finite(F) && finite(S) && allPts(F).length <= 120000
    && F.paths.every((q) => Number.isInteger(q.layer) && q.layer >= 0 && q.layer < 12));
  CHECK("[" + shape + "] deterministic", sig(o) === sig(run({ shape })));
}

/* --- Euler's formula from the mesh: V - E + F = 2 for every solid --- */
for (const shape of SHAPES) {
  const M = meshOf(run({ shape }));
  if (!M) { CHECK("[" + shape + "] Euler V-E+F=2", false, "no mesh"); continue; }
  const key = (i) => M.v.slice(i * 3, i * 3 + 3).map((t) => Math.round(t * 1e3)).join(",");
  const vs = new Map();
  const idx = [];
  for (let i = 0; i < M.tri * 3; i++) {
    const k = key(i);
    if (!vs.has(k)) vs.set(k, vs.size);
    idx.push(vs.get(k));
  }
  const edges = new Set();
  for (let t = 0; t < M.tri; t++) {
    const a = idx[t * 3], b = idx[t * 3 + 1], c = idx[t * 3 + 2];
    for (const [i, j] of [[a, b], [b, c], [c, a]]) edges.add(i < j ? i + "_" + j : j + "_" + i);
  }
  const V = vs.size, E = edges.size, F = M.tri;
  CHECK("[" + shape + "] Euler V-E+F=2", V - E + F === 2, "V" + V + " E" + E + " F" + F + " = " + (V - E + F));
}

/* --- known face counts, read from the drawn face outlines --- */
{
  const faceCount = (over) => facesOf(run({
    ...over, vis: "Transparent", fill: "None", edges: false, inset: 0,
  })).paths.length;
  const EXPECT = {
    "Tetrahedron": 4, "Cube": 6, "Octahedron": 8, "Dodecahedron": 12, "Icosahedron": 20,
    "Truncated tetrahedron": 8, "Truncated cube": 14, "Truncated octahedron": 14,
    "Truncated dodecahedron": 32, "Truncated icosahedron": 32,
    "Cuboctahedron": 14, "Icosidodecahedron": 32,
    "Rhombicuboctahedron": 26, "Rhombicosidodecahedron": 62,
    "Rhombic dodecahedron": 12, "Rhombic triacontahedron": 30,
  };
  for (const [shape, n] of Object.entries(EXPECT))
    CHECK("[" + shape + "] has " + n + " faces", faceCount({ shape }) === n, String(faceCount({ shape })));
  CHECK("Prism(6) has 8 faces", faceCount({ shape: "Prism", sides: 6 }) === 8);
  CHECK("Antiprism(6) has 14 faces", faceCount({ shape: "Antiprism", sides: 6 }) === 14);
  CHECK("Pyramid(6) has 7 faces", faceCount({ shape: "Pyramid", sides: 6 }) === 7);
  CHECK("Bipyramid(6) has 12 faces", faceCount({ shape: "Bipyramid", sides: 6 }) === 12);
  for (const [freq, n] of [[1, 20], [2, 80], [3, 320]])
    CHECK("Geodesic freq " + freq + " has " + n + " faces", faceCount({ shape: "Geodesic sphere", freq }) === n);
  CHECK("sides parameter changes the prism", faceCount({ shape: "Prism", sides: 3 }) === 5);
}

/* --- the mesh contract (v2.66) --- */
for (const shape of ["Cube", "Truncated icosahedron", "Geodesic sphere", "Bipyramid"]) {
  const M = meshOf(run({ shape }));
  CHECK("[" + shape + "] mesh: v.length === tri*9", M.v.length === M.tri * 9, M.v.length + " vs " + M.tri * 9);
  let mn = [Infinity, Infinity, Infinity], mx = [-Infinity, -Infinity, -Infinity];
  for (let i = 0; i < M.v.length; i += 3) for (let k = 0; k < 3; k++) {
    mn[k] = Math.min(mn[k], M.v[i + k]); mx[k] = Math.max(mx[k], M.v[i + k]);
  }
  const dim = [0, 1, 2].map((k) => mx[k] - mn[k]);
  CHECK("[" + shape + "] mesh normalised: longest dimension is 1", Math.abs(Math.max(...dim) - 1) < 2e-3, Math.max(...dim).toFixed(4));
  CHECK("[" + shape + "] mesh centred on the origin",
    [0, 1, 2].every((k) => Math.abs((mn[k] + mx[k]) / 2) < 2e-3));
  CHECK("[" + shape + "] mesh dims match the payload",
    [0, 1, 2].every((k) => Math.abs(M.dims[k] - dim[k]) < 2e-3));
  CHECK("[" + shape + "] mesh coordinates are finite", M.v.every((t) => Number.isFinite(t)));
}

/* --- Explode is a drawing convention, Stellate is real geometry --- */
{
  const a = meshOf(run({ shape: "Cube", explode: 0 }));
  const b = meshOf(run({ shape: "Cube", explode: 30 }));
  CHECK("Explode does NOT reach the mesh", JSON.stringify(a.v) === JSON.stringify(b.v));
  CHECK("Explode does change the drawing", sig(run({ shape: "Cube", explode: 0 })) !== sig(run({ shape: "Cube", explode: 30 })));
  const s0 = meshOf(run({ shape: "Icosahedron", stellate: 0 }));
  const s1 = meshOf(run({ shape: "Icosahedron", stellate: 0.8 }));
  CHECK("Stellate reshapes the mesh: 20 faces -> 60 triangles", s0.tri === 20 && s1.tri === 60, s0.tri + " -> " + s1.tri);
  CHECK("Stellate dimples inward too", sig(run({ shape: "Icosahedron", stellate: -0.4 })) !== sig(run({ shape: "Icosahedron", stellate: 0.4 })));
}

/* --- back-face culling --- */
{
  const solid = facesOf(run({ shape: "Cube", fill: "None", edges: false, inset: 0 })).paths.length;
  const trans = facesOf(run({ shape: "Cube", fill: "None", edges: false, inset: 0, vis: "Transparent" })).paths.length;
  CHECK("Solid mode culls the back of a cube (3 of 6)", solid === 3 && trans === 6, solid + " / " + trans);
  const xray = facesOf(run({ shape: "Cube", fill: "Concentric inset", vis: "X-ray (back thinned)" }));
  const tr2 = facesOf(run({ shape: "Cube", fill: "Concentric inset", vis: "Transparent" }));
  CHECK("X-ray keeps the back but thins it", xray.paths.length < tr2.paths.length && xray.paths.length > solid);
  /* every drawn face in Solid mode must face the camera: its projected
     outline must wind the same way (no mirrored, i.e. back-facing, loops) */
  const outs = facesOf(run({ shape: "Icosahedron", fill: "None", edges: false, inset: 0 })).paths;
  const area = (q) => {
    let a = 0;
    for (let i = 0; i < q.pts.length; i++) {
      const A = q.pts[i], B = q.pts[(i + 1) % q.pts.length];
      a += A[0] * B[1] - B[0] * A[1];
    }
    return a / 2;
  };
  const signs = new Set(outs.map((q) => Math.sign(area(q))));
  CHECK("every visible face winds the same way (all front-facing)", signs.size === 1, [...signs].join(","));
  CHECK("an icosahedron shows fewer than half its faces", outs.length > 0 && outs.length <= 10, String(outs.length));
}

/* --- silhouette --- */
for (const shape of ["Cube", "Icosahedron", "Truncated icosahedron", "Geodesic sphere"]) {
  const o = run({ shape });
  const sil = silOf(o).paths[0];
  CHECK("[" + shape + "] silhouette is one closed path", !!sil && sil.closed && sil.pts.length >= 3);
  /* convex: every turn the same sign */
  let signs = new Set();
  for (let i = 0; i < sil.pts.length; i++) {
    const A = sil.pts[i], B = sil.pts[(i + 1) % sil.pts.length], C = sil.pts[(i + 2) % sil.pts.length];
    const cr = (B[0] - A[0]) * (C[1] - B[1]) - (B[1] - A[1]) * (C[0] - B[0]);
    if (Math.abs(cr) > 1e-6) signs.add(Math.sign(cr));
  }
  CHECK("[" + shape + "] silhouette is convex", signs.size === 1);
  /* and it contains the whole drawing */
  const insideHull = (q) => sil.pts.every((_, i) => {
    const A = sil.pts[i], B = sil.pts[(i + 1) % sil.pts.length];
    const cr = (B[0] - A[0]) * (q[1] - A[1]) - (B[1] - A[1]) * (q[0] - A[0]);
    return signs.has(1) ? cr >= -0.05 : cr <= 0.05;
  });
  const stray = allPts(facesOf(o)).filter((q) => !insideHull(q));
  CHECK("[" + shape + "] silhouette contains every drawn point", stray.length === 0, stray.length + " outside");
}

/* --- even density compensation --- */
{
  const on = facesOf(run({ shape: "Cube", evenDensity: true })).paths.length;
  const off = facesOf(run({ shape: "Cube", evenDensity: false })).paths.length;
  CHECK("even density thins foreshortened faces", on < off, on + " vs " + off);
  CHECK("even density is live", sig(run({ shape: "Cube", evenDensity: true })) !== sig(run({ shape: "Cube", evenDensity: false })));
}

/* --- fills and parameter liveness --- */
{
  const FILLS = def.params.find((q) => q.key === "fill").options;
  CHECK("six fills plus None", FILLS.length === 7, String(FILLS.length));
  for (const fill of FILLS) {
    const o = run({ shape: "Dodecahedron", fill });
    CHECK("fill option renders: " + fill, facesOf(o).paths.length > 0 && finite(facesOf(o)));
  }
  CHECK("None draws only outlines",
    facesOf(run({ shape: "Cube", fill: "None", edges: false, inset: 0 })).paths.length
    < facesOf(run({ shape: "Cube", fill: "Concentric inset", edges: false, inset: 0 })).paths.length);
  const L = (a, b, name, base) => CHECK(name + " is live",
    sig(run({ ...(base || {}), ...a })) !== sig(run({ ...(base || {}), ...b })));
  L({ size: 60 }, { size: 200 }, "size");
  L({ x: 30 }, { x: 70 }, "x");
  L({ y: 30 }, { y: 70 }, "y");
  L({ rx: -40 }, { rx: 40 }, "rx");
  L({ ry: -40 }, { ry: 40 }, "ry");
  L({ rz: 0 }, { rz: 45 }, "rz");
  L({ persp: 0 }, { persp: 1 }, "persp");
  L({ step: 1.2 }, { step: 6 }, "step");
  L({ inset: 0 }, { inset: 6 }, "inset");
  L({ edges: true }, { edges: false }, "edges");
  L({ depthCue: 0 }, { depthCue: 1 }, "depthCue");
  L({ hatchAng: 0, fill: "Face hatch" }, { hatchAng: 90, fill: "Face hatch" }, "hatchAng");
  L({ dotSize: 0.6, fill: "Dots" }, { dotSize: 3, fill: "Dots" }, "dotSize");
  L({ freq: 1, shape: "Geodesic sphere" }, { freq: 3, shape: "Geodesic sphere" }, "freq");
  L({ layer: 0 }, { layer: 6 }, "layer");
  L({ pen2: 0, edges: true }, { pen2: 6, edges: true }, "pen2");
  for (const vis of def.params.find((q) => q.key === "vis").options)
    CHECK("visibility option renders: " + vis, facesOf(run({ vis })).paths.length > 0);
  const pens = new Set(facesOf(run({ layer: 3, pen2: 8, edges: true })).paths.map((q) => q.layer));
  CHECK("Pen and Edge pen both reach the output", pens.has(3) && pens.has(8), [...pens].join(","));
}

/* --- default view stays on an A4 sheet --- */
for (const shape of SHAPES) {
  const pts = allPts(facesOf(run({ shape })));
  const ok = pts.every((q) => q[0] >= -1 && q[0] <= 211 && q[1] >= -1 && q[1] <= 298);
  CHECK("[" + shape + "] default view fits the sheet", ok);
}

/* --- degenerate and extreme values --- */
{
  const cases = [
    { shape: "Geodesic sphere", freq: 4, fill: "Dots", step: 1, dotSize: 0.4 },
    { shape: "Rhombicosidodecahedron", fill: "Concentric inset", step: 0.6, inset: 0 },
    { shape: "Tetrahedron", inset: 12, size: 20 },
    { shape: "Cube", step: 12, inset: 0 },
    { shape: "Icosahedron", stellate: 2, explode: 60, persp: 1 },
    { shape: "Prism", sides: 16, fill: "Spiral", step: 0.6 },
    { shape: "Antiprism", sides: 3, fill: "Centroid fan", step: 0.6 },
  ];
  let ok = true, budget = true;
  for (const c of cases) {
    const o = run(c, SQ);
    if (!finite(facesOf(o)) || !finite(silOf(o))) ok = false;
    if (allPts(facesOf(o)).length > 120000) budget = false;
    const M = meshOf(o);
    if (M && (M.v.length !== M.tri * 9 || !M.v.every((t) => Number.isFinite(t)))) ok = false;
  }
  CHECK("extreme values: finite faces, silhouette and mesh", ok);
  CHECK("extreme values: point budget held", budget);
  const tiny = run({ shape: "Icosahedron", size: 20, inset: 12 }, { W: 60, H: 60 });
  CHECK("an inset larger than the face degrades to outlines", Array.isArray(facesOf(tiny).paths));
  let threw = false;
  try { def.compute([undefined], { ...defaults }, A4, { params: defaults }); } catch (e) { threw = true; }
  CHECK("unwired Style input does not throw", !threw);
}

/* --- overlay --- */
{
  let threw = false;
  try {
    for (const shape of SHAPES) {
      def.overlay({ ...defaults, shape }, A4, [null], { params: defaults });
      def.overlay({ ...defaults, shape, size: 20 }, { W: 60, H: 60 }, [null], { params: defaults });
    }
  } catch (e) { threw = true; }
  CHECK("overlay never throws", !threw);
  const ov = def.overlay({ ...defaults, x: 25, y: 75, size: 100 }, A4, [null], { params: defaults });
  const c = ov.find((g) => g.kind === "circle");
  CHECK("overlay circle sits at the body centre with the body radius",
    !!c && Math.abs(c.cx - 210 * 0.25) < 0.01 && Math.abs(c.cy - 297 * 0.75) < 0.01 && Math.abs(c.r - 50) < 0.01);
}

console.log((fail ? "FAILED " : "ALL OK ") + pass + " passed, " + fail + " failed");
process.exit(fail ? 1 : 0);
