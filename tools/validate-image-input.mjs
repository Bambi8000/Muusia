/** Blue Drawing input, tested with the actual Image and source nodes. */
import assert from 'node:assert/strict';
import {isDeepStrictEqual} from 'node:util';
import image from '../src/defs/nodes/image.js';
import {PENS} from '../src/defs/helpers.js';
import tracks from '../src/defs/nodes/radat.js';
import stroke from '../src/defs/nodes/viiva.js';
const defaults=d=>Object.fromEntries(d.params.map(p=>[p.key,p.def]));
const p={...defaults(image),mode:'Square weave',cell:2,margin:0,jitter:0,strength:1},ctx={W:80,H:60};
const path=(pts,closed=false,layer=0)=>({pts,closed,layer});
const src={paths:[path([[10,10],[70,10]],false,1),path([[10,25],[70,45]],false,4),path([[20,25],[30,25],[30,35],[20,35]],true,6)]};
const file={w:8,h:6,g:Array(48).fill(.8)};
const raster=(s=src,o={})=>image._drawingImage({...p,...o},ctx,s);
const run=(s=src,o={},img=file,style)=>image.compute([style,s],{...p,...o},ctx,{data:{img}});
let checks=0;const ok=(v,m)=>{assert.ok(v,m);checks++;};const eq=(a,b,m)=>{assert.ok(isDeepStrictEqual(a,b),m);checks++;};
const sample=(img,x,y)=>image._artSampler(img,image._artFit(p,ctx,img)).sample(x,y);
const geometry=r=>r.paths.map(({pts,closed})=>({pts,closed}));
eq(image.ins.map(p=>p.type),['style','paths'],'append Drawing without moving old Style input');
eq(image.ins[1].label,'Drawing','visible blue input');
const modes=image.params.find(p=>p.key==='mode').options;
for(const mode of modes){
 const r=run(src,{mode});ok(r.paths.length>0,mode+' accepts paths without a file');eq(r,run(src,{mode}),mode+' deterministic');
 ok(r.paths.every(q=>q.pts.every(pt=>pt.slice(0,2).every(Number.isFinite))),mode+' finite');
 eq(run(src,{mode},null),r,mode+' wired source overrides loaded file');
 eq(run(null,{mode,source:'Image (file)'}),run(src,{mode,source:'Image (file)'}),mode+' file override');
 eq(run({paths:[]},{mode}).paths,[],mode+' empty connected drawing never revives stored photo');
 eq(run(null,{mode,source:'Drawing (wired)'}).paths,[],mode+' explicit Drawing requires paths');
}
const saved=JSON.stringify(src);raster();eq(JSON.stringify(src),saved,'input is not mutated');
const r=raster();ok(sample(r,40,10)>.4,'open horizontal stroke in original canvas location');ok(sample(r,40,55)<.001,'white outside drawing');
ok(sample(r,25,32)<.001,'closed shape defaults to outline');
ok(sample(raster(src,{drawingFill:true}),25,32)>.4,'optional closed fill');
const rings={paths:[path([[10,10],[70,10],[70,50],[10,50]],true),path([[25,20],[55,20],[55,40],[25,40]],true)]};
const ringRaster=raster(rings,{drawingFill:true});ok(sample(ringRaster,15,30)>.8,'outer filled area');ok(sample(ringRaster,40,30)<.001,'nested same-pen hole remains clear');
const reversed={paths:rings.paths.map(q=>({...q,pts:[...q.pts].reverse()}))};
eq(raster(reversed,{drawingFill:true}),ringRaster,'fill independent of contour winding');
const separated={paths:[path([[5,5],[15,5]]),path([[65,55],[75,55]])]};ok(sample(raster(separated),40,30)<.001,'no pen-up links between paths');
const simple={paths:[path([[5,30],[75,30]])]},split={paths:[path([[5,30],[20,30],[40,30],[60,30],[75,30]])]};
eq(raster(simple),raster(split),'same segment coverage regardless of point count');
eq(raster({paths:[...simple.paths,...simple.paths]}),raster(simple),'duplicate stroke does not double its darkness');
const thin=raster(simple,{drawingWidth:.2}),thick=raster(simple,{drawingWidth:6});
ok(sample(thick,40,32)>.8&&sample(thin,40,32)<.001,'drawing width controls source coverage');
const off={paths:[path([[-1e9,30],[1e9,30]])]};ok(sample(raster(off),40,30)>.8,'off-page segment clips without disappearing');
const encompassing={paths:[path([[-100,-100],[200,-100],[200,200],[-100,200]],true)]};ok(sample(raster(encompassing,{drawingFill:true}),40,30)>.8,'filled shape enclosing canvas survives clipping');
const broken={paths:[path([[NaN,0],[20,20],[25,25]]),path(null),null]};ok(run(broken).paths.length>0,'malformed path does not hide valid segments');
eq(run({paths:[path([[NaN,0],[Infinity,0]])]}).paths,[],'fully invalid source is empty');
eq(image.compute([undefined,src],{...p,margin:60},ctx,{}).paths,[],'collapsed margin is empty');
for(const mode of ['Organic dots','Short strokes','Cross stitches','Square weave'])eq(geometry(run(src,{mode,colours:6})),geometry(run(src,{mode,colours:1})),mode+' output palette preserves drawing geometry');
const pixels=raster({paths:[path([[5,10],[75,10]],false,4)]});
const k=Math.floor(10/60*pixels.h)*pixels.w+Math.floor(40/80*pixels.w);
eq(Array.from(pixels.rgb.slice(k*3,k*3+3)),[1,3,5].map(i=>parseInt(PENS[4].c.slice(i,i+2),16)),'drawing samples actual source pen RGB');
const sty=stroke.compute([],{...defaults(stroke),mode:'Dashed',dash:.2,gap:.2},ctx);
ok(JSON.stringify(run(src,{},null,sty))!==JSON.stringify(run(src,{},null)),'Style remains applied to generated marks');
const t=tracks.compute([],{...defaults(tracks),rings:20,gap:1.2},ctx);const start=performance.now();const rr=run(t);ok(rr.paths.length>0,'real Tracks source');ok(rr.paths.reduce((a,q)=>a+q.pts.length,0)<=112000,'drawing obeys output budget');
const dense={paths:Array.from({length:3000},(_,i)=>path([[0,i%60],[80,(i*17)%60]],false,i%12))};const dr=raster(dense);
ok(Math.max(dr.w,dr.h)<640,'dense drawing adapts the complete raster');ok(sample(dr,20,20)>.3&&sample(dr,60,40)>.3,'dense source covers both sides');
const df=image._artFit(p,ctx,dr);eq(image.overlay(p,ctx,[undefined,dense],{}),[{kind:'rect',x:df.x,y:df.y,w:df.w,h:df.h}],'overlay matches adaptive drawing frame');
console.log(`Image Drawing input: ${checks} checks passed; Tracks → blocks ${Math.round(performance.now()-start)} ms including dense stress raster.`);
