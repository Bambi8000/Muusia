/* patch-docs-photo-trace.mjs — documentation batch for the photo_trace release.
   Run from the repo root AFTER baking photo_trace and bumping APP_VERSION:
     node tools/era/patch-docs-photo-trace.mjs
   Edits: docs/MUUSIA-NODES.md (header version + counts + node paragraph),
   docs/MUUSIA-TAGS.json (photo_trace entry), docs/MUUSIA-HANDOFF.md (version
   history bullet). Idempotent per file, MISS-aborts per file (nothing written
   on any miss in that file), version and counts read from the repo at runtime. */

import { readFileSync, writeFileSync, readdirSync } from "node:fs";

let anyFail = 0;
const OK = (m) => console.log("OK    " + m);
const SKIP = (m) => console.log("SKIP  " + m);
const MISS = (m) => { console.log("MISS  " + m); anyFail++; };

/* ---- facts from the repo ---- */
const app = readFileSync("src/App.jsx", "utf8");
const vm = app.match(/APP_VERSION = "([^"]+)"/);
if (!vm) { console.log("MISS  APP_VERSION not found - ABORT"); process.exit(1); }
const V = vm[1];
const nodeFiles = readdirSync("src/defs/nodes").filter((f) => f.endsWith(".js"));
const TOTAL = nodeFiles.length + 2; /* + inline group/reititys DEFS in App.jsx */
let GENS = 0;
for (const f of nodeFiles) {
  if (/cat:\s*"gen"/.test(readFileSync("src/defs/nodes/" + f, "utf8"))) GENS++;
}
if (!nodeFiles.includes("photo_trace.js")) {
  console.log("MISS  src/defs/nodes/photo_trace.js not baked yet - ABORT (bake first)");
  process.exit(1);
}
console.log("INFO  version " + V + ", " + TOTAL + " nodes total, " + GENS + " generators (from disk)");

const PARA = `**Photo Trace** — recovers a real object's outline at true physical size and
position from a photo. Print \`public/markers/muusia-markers-a4.png\` (or \`-a3\`)
at 100% scale — the bar on the sheet must measure exactly 100.0 mm — lay the
object on the sheet, photograph it from as overhead as possible and load the
photo. The four 15 mm corner markers (the hollow one is the orientation anchor,
so any camera rotation works) fix a pixel→millimetre perspective homography; the
largest dark shape inside them is contour-traced into one closed path.
*Threshold* and *Invert* set the dark cutoff, *Simplify* (RDP) and *Smooth*
(Chaikin) clean the contour, *Grow* offsets it outward in mm for glue clearance
(negative shrinks), *Rotate* matches how the printed sheet lies on the plotter
bed, and *As photographed* keeps the outline exactly where the object lay — plot
around the blank spot, then glue the object back in. Chain into Wind Tunnel's
Obstacle or Container. The sheet plane is perspective-corrected but object
height adds a small safe-side parallax, so tall objects trace slightly large.`;

const BULLET = `- **${V}** **Photo Trace** (gen/textimg) baked, plus printable marker sheets
  (\`public/markers/muusia-markers-a4.png\` / \`-a3.png\`, generated by the new
  zero-dependency \`tools/make-marker-sheets.mjs\` — 300 DPI grayscale PNG via
  node:zlib with a 5×7 bitmap font and a 100 mm verification bar). Photograph
  an object on the printed sheet and the node recovers its outline at true
  physical size and position: 3 solid + 1 donut (anchor) 15 mm corner markers
  → per-image-corner blob pick → 4-point DLT homography px→mm → largest
  interior blob → Moore contour trace → RDP → Chaikin → normal-offset Grow.
  The validator synthesizes the sheet and a known ellipse under a known
  perspective homography and proves recovery to ≤0.27 mm (centroid ≤0.22 mm)
  in all four camera rotations, with the sheet's own scale bar and text row
  present as decoy blobs; supersampled soft edges keep Threshold testable.
  imageMax 1200 (engine allows up to 1600), ~14 ms/compute at full
  resolution. Intended chain: Photo Trace → Wind Tunnel Obstacle — plot the
  flow around the blank spot, then glue the object into it.`;

/* ---- docs/MUUSIA-NODES.md ---- */
{
  const FILE = "docs/MUUSIA-NODES.md";
  let src = readFileSync(FILE, "utf8");
  if (src.includes("**Photo Trace**")) {
    SKIP(FILE + " already has Photo Trace");
  } else {
    let miss = 0, txt = src;
    const hv = txt.match(/^# MUUSIA v([\d.]+) — Node Reference$/m);
    if (!hv) { MISS(FILE + ": header version line not found"); miss++; }
    const tv = txt.match(/All (\d+) built-in nodes/);
    if (!tv) { MISS(FILE + ": total count not found"); miss++; }
    else if (Number(tv[1]) !== TOTAL - 1) { MISS(FILE + ": total is " + tv[1] + ", expected " + (TOTAL - 1)); miss++; }
    const gv = txt.match(/^## Generators \((\d+)\)$/m);
    if (!gv) { MISS(FILE + ": Generators heading not found"); miss++; }
    else if (Number(gv[1]) !== GENS - 1) { MISS(FILE + ": Generators is " + gv[1] + ", expected " + (GENS - 1)); miss++; }
    if (!miss) {
      const edits = [
        [hv[0], "# MUUSIA v" + V + " — Node Reference"],
        ["All " + tv[1] + " built-in nodes", "All " + TOTAL + " built-in nodes"],
        ["## Generators (" + gv[1] + ")\n\n", "## Generators (" + GENS + ")\n\n" + PARA + "\n\n"],
      ];
      for (const [o, n] of edits) {
        const parts = txt.split(o);
        if (parts.length === 2) txt = parts.join(n);
        else { MISS(FILE + ": anchor '" + o.slice(0, 40) + "...' " + (parts.length - 1) + " hits"); miss++; }
      }
    }
    if (miss) { console.log("ABORT " + FILE + " NOT written"); }
    else { writeFileSync(FILE, txt); OK(FILE + " (version " + V + ", " + TOTAL + " nodes, " + GENS + " generators, paragraph inserted)"); }
  }
}

/* ---- docs/MUUSIA-TAGS.json ---- */
{
  const FILE = "docs/MUUSIA-TAGS.json";
  const raw = readFileSync(FILE, "utf8");
  const obj = JSON.parse(raw);
  if (obj.photo_trace) {
    SKIP(FILE + " already has photo_trace");
  } else if (JSON.stringify(obj, null, 1) + "\n" !== raw && JSON.stringify(obj, null, 1) !== raw) {
    MISS(FILE + ": formatting is not JSON.stringify(,null,1) - refusing to rewrite, add photo_trace manually");
  } else {
    obj.photo_trace = ["image", "region"];
    const sorted = {};
    for (const k of Object.keys(obj).sort()) sorted[k] = obj[k];
    writeFileSync(FILE, JSON.stringify(sorted, null, 1) + (raw.endsWith("\n") ? "\n" : ""));
    OK(FILE + " (photo_trace: image, region)");
  }
}

/* ---- docs/MUUSIA-HANDOFF.md ---- */
{
  const FILE = "docs/MUUSIA-HANDOFF.md";
  let src = readFileSync(FILE, "utf8");
  if (src.includes("** **Photo Trace** (gen/textimg) baked")) {
    SKIP(FILE + " already has the version bullet");
  } else {
    const anchor = "\n\n## Hard-won pitfalls (keep)";
    const parts = src.split(anchor);
    if (parts.length !== 2) {
      MISS(FILE + ": pitfalls heading anchor " + (parts.length - 1) + " hits");
      console.log("ABORT " + FILE + " NOT written");
    } else {
      writeFileSync(FILE, parts[0] + "\n" + BULLET + anchor + parts[1]);
      OK(FILE + " (version history bullet " + V + ")");
    }
  }
}

console.log(anyFail === 0 ? "DONE" : "DONE WITH " + anyFail + " MISSES - fix and re-run");
process.exit(anyFail === 0 ? 0 : 1);
