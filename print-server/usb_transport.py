"""Bounded, acknowledged Epson USB transfers; no blind retry after lost framing.

GS ( H function 48 replies after preceding print data completes:
https://download4.epson.biz/sec_pubs/pos/reference_en/escpos/gs_lparen_ch_fn48.html
The exported program stays unchanged; only the live USB bands are subdivided.
"""

import os
import select
import time
import uuid

BAND_ROWS = 32  # 2056 bytes including GS v 0 header, below the 4 KiB RX buffer.
TIMEOUT = 30
failure = None  # A failed live transfer requires a service restart after recovery.


def segments(data):
    """Walk server-generated programs, skipping raster payloads by their lengths.

    Native text generated by native_fonts cannot contain GS control bytes.
    Never search inside a bitmap: it may contain arbitrary command-like bytes.
    Validate the whole program before opening the printer.
    """
    result, position = [], 0
    while position < len(data):
        start = data.find(b'\x1dv0', position)
        if start < 0:
            result.append((data[position:], 0))
            break
        if start > position:
            result.append((data[position:start], 0))
        if start + 8 > len(data):
            raise ValueError('Truncated raster header')
        header = data[start:start + 8]
        stride = header[4] + 256 * header[5]
        height = header[6] + 256 * header[7]
        end = start + 8 + stride * height
        if header[3] != 0 or stride != 64 or not 1 <= height <= 256 or end > len(data):
            raise ValueError('Invalid generated raster band')
        for row in range(0, height, BAND_ROWS):
            rows = min(BAND_ROWS, height - row)
            band = b'\x1dv0\x00\x40\x00' + bytes((rows, 0))
            band += data[start + 8 + row * stride:start + 8 + (row + rows) * stride]
            result.append((band, rows))
        position = end
    return result


def write_usb(fd, data, timeout=TIMEOUT):
    view = memoryview(data)
    deadline = time.monotonic() + timeout
    while view:
        remaining = deadline - time.monotonic()
        if remaining <= 0 or not select.select([], [fd], [], remaining)[1]:
            raise TimeoutError('USB printer stopped accepting data')
        try:
            written = os.write(fd, view[:1024])
        except (BlockingIOError, InterruptedError):
            continue
        if written <= 0:
            raise OSError('USB printer stopped accepting data')
        view = view[written:]


def acknowledge(fd, token, timeout=TIMEOUT):
    write_usb(fd, b'\x1d(H\x06\x0000' + token, timeout)
    expected = b'7"' + token + b'\x00'
    received = bytearray()
    deadline = time.monotonic() + timeout
    while True:
        remaining = deadline - time.monotonic()
        if remaining <= 0 or not select.select([fd], [], [], remaining)[0]:
            raise TimeoutError('Printer acknowledgement missing; power-cycle printer and restart Print before retrying')
        try:
            part = os.read(fd, 1024)
        except (BlockingIOError, InterruptedError):
            continue
        if not part:
            # usblp may complete an IN transfer with a zero-length USB packet.
            # It is not a stream EOF; a real detach raises ENODEV/EIO. Keep the
            # same deadline, without spinning on empty completions.
            time.sleep(0.01)
            continue
        received.extend(part)
        if expected in received:
            return
        # Ignore ASB, real-time status bytes and stale process IDs. All replies
        # are short; retain only enough tail for an acknowledgement split.
        del received[:-len(expected)]


def print_program(fd, parts, progress=None):
    sequence = int(uuid.uuid4().hex[:4], 16)
    def ack():
        nonlocal sequence
        sequence = (sequence + 1) % 65536
        acknowledge(fd, f'{sequence:04X}'.encode('ascii'))
    # Probe before sending image bytes. No fallback to unacknowledged writes.
    ack()
    rows_done = 0
    for data, rows in parts:
        write_usb(fd, data)
        ack()
        rows_done += rows
        if progress:
            progress(rows_done)
